use std::path::PathBuf;

use crate::cargo::{self, Diagnostic, Severity};
use crate::dashboard::Dashboard;
use crate::format;

#[derive(Clone, Debug)]
pub struct ReportData {
    pub root: PathBuf,
    pub mode: String,
    pub buffers: Vec<String>,
    pub buffer_count: usize,
    pub windows: Vec<String>,
    pub window_count: usize,
    pub diagnostics: Vec<Diagnostic>,
    pub tasks: usize,
    pub notes: usize,
    pub job: Option<String>,
}

impl From<&Dashboard> for ReportData {
    fn from(dashboard: &Dashboard) -> Self {
        Self {
            root: dashboard.root.clone(),
            mode: dashboard.mode.clone(),
            buffers: dashboard.buffers.clone(),
            buffer_count: dashboard.buffer_count,
            windows: dashboard.windows.clone(),
            window_count: dashboard.window_count,
            diagnostics: dashboard.diagnostics.clone(),
            tasks: dashboard.tasks,
            notes: dashboard.notes,
            job: dashboard.job.clone(),
        }
    }
}

pub fn render(data: &ReportData) -> String {
    let mut report = String::new();
    report.push_str(&format!(
        "# Project Cockpit: {}\n\n",
        format::root_name(&data.root)
    ));
    report.push_str("Generated by the Kawi cockpit plugin.\n\n");
    report.push_str("## Project\n\n");
    report.push_str(&format!("- Root: `{}`\n", data.root.display()));
    report.push_str(&format!("- Mode: `{}`\n\n", data.mode));
    report.push_str("## Buffers\n\n");
    report.push_str(&format!(
        "- Open: {} ({} listed)\n",
        data.buffer_count,
        data.buffers.len()
    ));
    for buffer in &data.buffers {
        report.push_str(&format!("- `{buffer}`\n"));
    }
    report.push_str("\n## Windows\n\n");
    report.push_str(&format!("- Open: {}\n", data.window_count));
    for window in &data.windows {
        report.push_str(&format!("- `{window}`\n"));
    }
    report.push_str("\n## Diagnostics\n\n");
    let errors = cargo::count(&data.diagnostics, Severity::Error);
    let warnings = cargo::count(&data.diagnostics, Severity::Warning);
    report.push_str(&format!(
        "- {} total, {}, {}\n",
        data.diagnostics.len(),
        format::count_label(errors, "error"),
        format::count_label(warnings, "warning")
    ));
    for diagnostic in &data.diagnostics {
        report.push_str(&format!("- `{}`\n", diagnostic.render(&data.root)));
    }
    report.push_str("\n## Tasks and notes\n\n");
    report.push_str(&format!("- Tasks: {}\n", data.tasks));
    report.push_str(&format!("- Notes: {}\n", data.notes));
    if let Some(job) = &data.job {
        report.push_str(&format!("- Last job: {job}\n"));
    }
    report
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cargo::parse;

    fn sample() -> ReportData {
        ReportData {
            root: PathBuf::from("/work/demo"),
            mode: "normal".to_string(),
            buffers: vec!["main.rs".to_string()],
            buffer_count: 1,
            windows: vec!["1 active".to_string()],
            window_count: 1,
            diagnostics: parse("src/main.rs:1:1: error: bad\n"),
            tasks: 4,
            notes: 2,
            job: Some("succeeded".to_string()),
        }
    }

    #[test]
    fn renders_all_sections() {
        let report = render(&sample());
        assert!(report.starts_with("# Project Cockpit: demo\n"));
        assert!(report.contains("- Root: `/work/demo`"));
        assert!(report.contains("- `main.rs`"));
        assert!(report.contains("- 1 total, 1 error, 0 warnings"));
        assert!(report.contains("- Tasks: 4"));
        assert!(report.contains("- Last job: succeeded"));
    }

    #[test]
    fn omits_a_missing_job() {
        let mut data = sample();
        data.job = None;
        assert!(!render(&data).contains("Last job"));
    }
}
